export const spelling = text => text.replace(/[\u064B-\u0652]/gu, "").replace(/[،.]/gu, "").trim();

export function speechFor(id, canonicalText) {
  const derived = deriveSpeechText(id, canonicalText);
  if (derived.strategy !== "official-emlaey-aligned") return derived;
  const key = id === "moia-mukhtasar-1446-tawaf-between-corners" ? "001" : id.replace("moia-mukhtasar-1446-general-", "");
  const speechText = vowelled.get(key);
  assert.ok(speechText, `${id}: missing speech-only vowels`);
  assert.equal(spelling(speechText), spelling(derived.speechText), `${id}: speech words differ from official spelling`);
  assert.ok(!SPECIAL_SPEECH_MARKS.test(speechText));
  return { ...derived, speechText, strategy: "official-emlaey-with-ordinary-vowels" };
}
